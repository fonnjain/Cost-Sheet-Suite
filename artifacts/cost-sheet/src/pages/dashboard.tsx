// ---- KPI Card ----
function KpiCard({
  label, value, unit, sub, accent = false,
}: { label: string; value: string; unit?: string; sub?: string; accent?: boolean }) {
  return (
    <div className={`relative overflow-hidden rounded-xl border p-5 ${
      accent
        ? "bg-gradient-to-br from-primary/16 to-primary/5 border-primary/30"
        : "bg-gradient-to-br from-card to-card/70 border-border/60"
    }`}>
      <div className="absolute top-0 left-0 w-full h-[3px] bg-gradient-to-r from-primary via-accent2 to-transparent opacity-70" />
      <div className="text-[10px] tracking-[0.14em] uppercase font-mono text-muted-foreground mb-2">{label}</div>
      <div className="flex items-baseline gap-1.5">
        <span className="text-[26px] font-mono font-bold leading-none text-foreground">{value}</span>
        {unit && <span className="text-xs font-mono text-muted-foreground">{unit}</span>}
      </div>
      {sub && <div className="mt-1.5 text-[10.5px] font-mono text-muted-foreground">{sub}</div>}
    </div>
  );
}

