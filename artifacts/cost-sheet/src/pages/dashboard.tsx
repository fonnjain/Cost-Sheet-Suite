// ---- Palette (matching HTML reference) ----
const PALETTE = {
  accent:  "#e63329",
  accent2: "#ff6a3c",
  steel:   "#3d6ea5",
  steelLt: "#6f9bd1",
  mist:    "#aebccd",
  slate:   "#5b708a",
  ok:      "#34d399",
  gridline:"rgba(174,188,205,.12)",
  txt:     "#aebccd",
};

const DONUT_COLORS = [
  PALETTE.accent, PALETTE.accent2, PALETTE.steel,
  PALETTE.steelLt, PALETTE.ok, PALETTE.slate, PALETTE.mist,
];

const MARGIN_LEVELS = [0.03, 0.04, 0.05, 0.06, 0.07, 0.08, 0.10];

interface CB {
  steelLanded: number; scrapCost: number; recoveryCost: number; rmNet: number;
  zincCost: number; convTotal: number; protoCostPerMt: number;
  wipSteelCost: number; wipZincCost: number; financeCost: number;
  contingency: number; baseForCredit: number; creditTotal: number;
  totalBeforeMargin: number; quotePrice: number;
}

function getBreakdownSections(cb: CB) {
  return [
    { name: "RM Net", value: cb.rmNet },
    { name: "Zinc", value: cb.zincCost },
    { name: "Conversion", value: cb.convTotal },
    { name: "Proto", value: cb.protoCostPerMt },
    { name: "Finance", value: cb.financeCost },
    { name: "Contingency", value: cb.contingency },
    { name: "Credit", value: cb.creditTotal },
  ].filter(s => s.value > 0.01);
}

function getMarginScenarios(totalBeforeMargin: number) {
  return MARGIN_LEVELS.map(m => ({
    label: `${(m * 100).toFixed(0)}%`,
    cost: Math.round(totalBeforeMargin),
    quote: Math.round(totalBeforeMargin / (1 - m)),
  }));
}

// ---- Export (mirrors HTML reference format exactly) ----
function exportCostSheet(quote: Quote) {
  const cb = quote.costBreakdown as unknown as CB;
  const inp = quote.inputs as unknown as Record<string, number>;
  const fmtPct = (v: number, d = 1) => `${(v * 100).toFixed(d)}%`;

  const aoa: (string | number)[][] = [];
  aoa.push([`COST ANALYSIS — ${quote.structureType}${quote.kvOption ? " (" + quote.kvOption + ")" : ""}`]);
  aoa.push([]);
  aoa.push(["Client:", quote.customerName, "", "Date:", format(new Date(quote.createdAt), "dd MMM yyyy")]);
  aoa.push(["Project:", quote.projectRef, "", "Rev:", `Rev ${quote.revision}`]);
  aoa.push(["Generated By:", quote.generatedByName]);
  aoa.push([]);
  aoa.push(["#", "Section / Item", "Notes", "Sub Total", "Total (₹/MT)"]);

  // Steel
  aoa.push(["1", "Steel"]);
  aoa.push(["", "  Steel Base Price", "", "", inp.steelBasePrice]);
  aoa.push(["", "  Incidental Charges", "", inp.incidental || 0, ""]);
  aoa.push(["", "  Landed Price", "", cb.steelLanded, ""]);
  aoa.push(["", "  Scrap", fmtPct(inp.scrapPct || 0), cb.scrapCost, ""]);
  aoa.push(["", "  Recovery", fmtPct(inp.recoveryPct || 0), cb.recoveryCost, cb.rmNet]);

  // Zinc
  aoa.push(["2", "Zinc", `${inp.zincPrice} × ${fmtPct(inp.zincMicron || 0, 3)}`, "", cb.zincCost]);

  // Conversion
  aoa.push(["3", "Conversion", "", "", cb.convTotal]);
  const convFields: [string, string][] = [
    ["Fabrication – Labour", "fabLabor"],
    ["Welding & Consumables", "weldCons"],
    ["Galvanising – Fuel & Labour", "galvFl"],
    ["Packing & Straightening", "packStrn"],
    ["Loading & Unloading", "loadUnload"],
    ["Handing Over Charge", "handover"],
    ["Others", "others"],
  ];
  for (const [lbl, k] of convFields) {
    const v = inp[k] || 0;
    if (v) aoa.push(["", "  " + lbl, "", v, ""]);
  }

  // Proto
  if (cb.protoCostPerMt > 0) {
    aoa.push(["4", "Proto Fab & Assembly",
      `${inp.protoCost} × ${fmtPct(inp.protoPct || 0)}`, "", cb.protoCostPerMt]);
  }

  // Financing
  aoa.push(["5", "Financing", "", "", cb.financeCost]);
  aoa.push(["", "  WIP (Steel)",
    `${inp.wipSteelMonths}mo @ ${fmtPct(inp.wipSteelRate || 0, 2)}`, cb.wipSteelCost, ""]);
  aoa.push(["", "  WIP (Zinc)",
    `${inp.wipZincMonths}mo @ ${fmtPct(inp.wipZincRate || 0, 2)}`, cb.wipZincCost, ""]);

  // Contractual
  aoa.push(["6", "Contractual", "", "", cb.contingency]);
  const contFields: [string, string][] = [
    ["Inspection + Insurance", "inspectIns"],
    ["Special Packing", "spPacking"],
    ["Freight Outward", "freightOut"],
    ["Third Party Testing", "thirdParty"],
    ["Agency Commission", "agencyComm"],
    ["BG Cost", "bgCost"],
  ];
  for (const [lbl, k] of contFields) {
    const v = inp[k] || 0;
    if (v) aoa.push(["", "  " + lbl, "", v, ""]);
  }

  aoa.push(["", "SUBTOTAL (before credit)", "", "", cb.baseForCredit]);

  // Credit Cost
  aoa.push(["7", "Credit Cost", "", "", cb.creditTotal]);
  const creditFields: [string, string][] = [
    ["Open (Part)", "openPo"],
    ["Open (Final)", "finalPayment"],
    ["EMD", "emd"],
    ["LC", "lc"],
    ["VFS", "vfs"],
    ["ABG", "abg"],
    ["PBG", "pbg"],
    ["CPBG", "cpbg"],
    ["Advance", "advance"],
  ];
  for (const [lbl, k] of creditFields) {
    const rate = inp[`${k}Rate`] || 0;
    const months = inp[`${k}Months`] || 0;
    const pct = inp[`${k}Pct`] || 0;
    const cost = (rate * months / 12) * pct * cb.baseForCredit;
    if (Math.abs(cost) > 0.01)
      aoa.push(["", "  " + lbl,
        `${fmtPct(rate, 3)} × ${months}mo × ${fmtPct(pct)}`, "", cost]);
  }

  aoa.push(["8", "TOTAL LANDED COST", "", "", cb.totalBeforeMargin]);
  aoa.push([]);
  aoa.push(["9", "Margin scenarios"]);
  aoa.push(["", "Margin %", "Margin (₹/MT)", "Quote (₹/MT)"]);
  for (const m of MARGIN_LEVELS) {
    const q = cb.totalBeforeMargin / (1 - m);
    aoa.push(["", fmtPct(m, 1), q - cb.totalBeforeMargin, q]);
  }
  aoa.push([]);
  const recPct = inp.marginPct || 0.05;
  const recQuote = cb.quotePrice;
  aoa.push(["10", "RECOMMENDED QUOTE",
    `${fmtPct(recPct, 1)} margin`, recQuote + " /MT", recQuote]);

  const ws = XLSX.utils.aoa_to_sheet(aoa);
  ws["!cols"] = [{ wch: 4 }, { wch: 36 }, { wch: 30 }, { wch: 14 }, { wch: 16 }];
  // Number format all numeric cells
  for (const addr in ws) {
    if (addr.startsWith("!")) continue;
    const cell = ws[addr];
    if (typeof cell.v === "number") cell.z = "#,##0";
  }

  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, "Cost Analysis");

  // Inputs snapshot sheet
  const inpAoa: (string | number)[][] = [
    ["INPUT SNAPSHOT"], [],
    ["Structure", quote.structureType],
    ["kV Option", quote.kvOption || ""],
    ["Client", quote.customerName],
    ["Project", quote.projectRef],
    ["Date generated", format(new Date(quote.createdAt), "dd MMM yyyy")],
    [],
    ["Parameter", "Value"],
  ];
  for (const [k, v] of Object.entries(inp)) {
    inpAoa.push([k, typeof v === "number" ? v : String(v)]);
  }
  const wsIn = XLSX.utils.aoa_to_sheet(inpAoa);
  wsIn["!cols"] = [{ wch: 28 }, { wch: 20 }];
  XLSX.utils.book_append_sheet(wb, wsIn, "Inputs");

  const stamp = format(new Date(), "yyMMdd_HHmm");
  const safe = quote.structureType.replace(/[^A-Za-z0-9]/g, "_").replace(/_+/g, "_").slice(0, 30);
  XLSX.writeFile(wb, `CostSheet_${safe}_${stamp}.xlsx`);
}

